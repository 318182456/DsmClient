  static String value(String key, dynamic value, {String context = ''}) {
    final k = normalize(key);
    if (value == null) return '—';
    if (value is bool) return value ? '是' : '否';
    if (context == 'qb-tracker' && k == 'status')
      return const {
            '0': '已停用',
            '1': '尚未联系',
            '2': '正常',
            '3': '更新中',
            '4': '未正常工作',
            '5': '服务器错误',
            '6': '无法连接'
          }['$value'] ??
          '$value';
    if (context == 'transmission' && (k == 'status' || k == 'state'))
      return const {
            '0': '已暂停',
            '1': '等待校验',
            '2': '校验中',
            '3': '排队下载',
            '4': '下载中',
            '5': '排队做种',
            '6': '做种中'
          }['$value'] ??
          '$value';
    if (const {
      'state',
      'status',
      'health',
      'healthstatus',
      'msg',
      'lastannounceresult',
      'lastscraperesult',
      'clientstatus',
      'clienttype'
    }.contains(k)) return status(value);
    if (k == 'restartpolicy' || (context == 'restart-policy' && k == 'name'))
      return const {
            'no': '不自动重启',
            'always': '始终重启',
            'unless-stopped': '停止前保持重启',
            'on-failure': '失败时重启'
          }['$value'] ??
          '$value';
    return '$value';
  }

  static String tracker(Map row, {bool transmission = false}) {
    final message = '${row['msg'] ?? row['lastAnnounceResult'] ?? ''}';
    if (message.isNotEmpty) return status(message);
    if (row['updating'] == true) return '更新中';
    return value('status', row['status'],
        context: transmission ? '' : 'qb-tracker');
  }
